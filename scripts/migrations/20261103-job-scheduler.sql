-- 通用任务定义与执行历史。时间均为 epoch 毫秒，Cron 时区另存。
CREATE TABLE sys_job (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 group_name VARCHAR(64) NOT NULL,
 handler VARCHAR(64) NOT NULL,
 parameters VARCHAR(4000) NOT NULL,
 schedule_type VARCHAR(16) NOT NULL,
 cron VARCHAR(120),
 interval_seconds INT,
 zone_id VARCHAR(64) NOT NULL,
 misfire_policy VARCHAR(16) NOT NULL,
 timeout_seconds INT NOT NULL,
 max_retries INT NOT NULL DEFAULT 0,
 retry_delay_seconds INT NOT NULL DEFAULT 30,
 retention_days INT NOT NULL DEFAULT 30,
 status VARCHAR(16) NOT NULL DEFAULT 'PAUSED',
 version BIGINT NOT NULL DEFAULT 1,
 synced_version BIGINT NOT NULL DEFAULT 0,
 sync_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 sync_error VARCHAR(500),
 active_run_id BIGINT,
 next_fire_at BIGINT,
 last_started_at BIGINT,
 last_status VARCHAR(16),
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 INDEX idx_job_status(status, id),
 INDEX idx_job_sync(sync_status, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE sys_job_execution (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 job_id BIGINT NOT NULL,
 job_name VARCHAR(100) NOT NULL,
 job_version BIGINT NOT NULL,
 handler VARCHAR(64) NOT NULL,
 parameters VARCHAR(4000) NOT NULL,
 config_snapshot TEXT NOT NULL,
 source VARCHAR(16) NOT NULL,
 actor_id BIGINT,
 actor_name VARCHAR(64),
 status VARCHAR(16) NOT NULL,
 attempt INT NOT NULL DEFAULT 0,
 parent_run_id BIGINT,
 scheduled_at BIGINT NOT NULL,
 started_at BIGINT,
 finished_at BIGINT,
 heartbeat_at BIGINT,
 duration_ms BIGINT,
 instance_id VARCHAR(200),
 trace_id VARCHAR(64) NOT NULL,
 succeeded BIGINT NOT NULL DEFAULT 0,
 failed BIGINT NOT NULL DEFAULT 0,
 summary VARCHAR(1000),
 resolution VARCHAR(500),
 created_at BIGINT NOT NULL,
 INDEX idx_job_execution_job(job_id, created_at, id),
 INDEX idx_job_execution_state(status, heartbeat_at),
 INDEX idx_job_execution_end(finished_at, id),
 INDEX idx_job_execution_queue(status, scheduled_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
